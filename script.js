/* =========================================================
   GET NESTED TRANSLATION
========================================================= */

function getTranslation(
    language,
    key
) {

    const parts =
        key.split(".");

    let value =
        translations[language];

    for (
        const part of parts
    ) {

        if (
            value &&
            value[part] !== undefined
        ) {

            value =
                value[part];

        } else {

            return null;

        }

    }

    return value;

}


/* =========================================================
   TRANSLATE WEBSITE
========================================================= */

function translateWebsite(
    language
) {

    if (
        !translations[language]
    ) {

        language = "en";

    }


    /*
        Translate all normal elements
    */

    const elements =
        document.querySelectorAll(
            "[data-i18n]"
        );


    elements.forEach(
        element => {

            const key =
                element.dataset.i18n;

            const translated =
                getTranslation(
                    language,
                    key
                );


            if (
                translated !== null
            ) {

                element.textContent =
                    translated;

            }

        }
    );


    /*
        Change HTML language
    */

    document.documentElement.lang =
        language;


    /*
        Update both selectors
    */

    languageSelector.value =
        language;

    footerLanguage.value =
        language;


    /*
        Save language
    */

    localStorage.setItem(
        "cr7-language",
        language
    );


    /*
        Change direction for future
        RTL languages if needed.
    */

    document.body.dir =
        "ltr";

}


